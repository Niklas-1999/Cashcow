export function line(personality, event, vars = {}) {
  const set = D[personality] || D.genki;
  const arr = set[event] || D.genki[event] || ['...'];
  return pick(arr).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

